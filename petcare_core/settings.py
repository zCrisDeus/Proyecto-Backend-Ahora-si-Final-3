# Filled at boot from EC2 metadata by the systemd pre-start helper.
# A configured domain remains the preferred URL, if one is provided later.
import ipaddress
_ip_file = os.environ.get('PETCARE_PUBLIC_IP_FILE', '')
if _ip_file:
    try:
        _ip = str(ipaddress.IPv4Address(Path(_ip_file).read_text().strip()))
    except (OSError, ValueError) as exc:
        raise ImproperlyConfigured('No se pudo leer una IPv4 válida de la configuración de arranque.') from exc
    ALLOWED_HOSTS = list(dict.fromkeys(ALLOWED_HOSTS + [_ip]))
    if not os.environ.get('PUBLIC_BASE_URL'):
        PUBLIC_BASE_URL = 'http://' + _ip
